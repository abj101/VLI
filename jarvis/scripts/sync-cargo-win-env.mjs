#!/usr/bin/env node

/**
 * Writes `src-tauri/.cargo/config.local.toml` so bare `cargo check` / rust-analyzer get the same
 * whisper-rs-sys env as `scripts/whisper-gpu/run-tauri.mjs`.
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

import { resolveBuildEnvironment } from "./build-environment.mjs";
import { tomlEnvValue, validateWindowsWhisperBindgenEnv } from "./whisper-gpu/win-env.mjs";

const JARVIS_ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
/** Included from `src-tauri/.cargo/config.toml` (pulled in by `jarvis/.cargo/config.toml`). */
const TAURI_CARGO_DIR = path.join(JARVIS_ROOT, "src-tauri", ".cargo");
const WINDOWS_TARGET = "x86_64-pc-windows-msvc";

function writeRustAnalyzerToml(discovered) {
  const bindgen = discovered.BINDGEN_EXTRA_CLANG_ARGS;
  const libClang = discovered.LIBCLANG_PATH;
  if (!bindgen && !libClang) return;

  /** @type {Record<string, string>} */
  const extraEnv = {};
  if (libClang) extraEnv.LIBCLANG_PATH = libClang;
  if (bindgen) {
    extraEnv.BINDGEN_EXTRA_CLANG_ARGS = bindgen;
    extraEnv.BINDGEN_EXTRA_CLANG_ARGS_x86_64_pc_windows_msvc = bindgen;
    extraEnv["BINDGEN_EXTRA_CLANG_ARGS_x86_64-pc-windows-msvc"] = bindgen;
  }
  if (discovered.CMAKE_GENERATOR) {
    extraEnv.CMAKE_GENERATOR = discovered.CMAKE_GENERATOR;
  }
  if (discovered.CMAKE_MAKE_PROGRAM) {
    extraEnv.CMAKE_MAKE_PROGRAM = discovered.CMAKE_MAKE_PROGRAM;
  }

  const lines = [
    "# Generated by scripts/sync-cargo-win-env.mjs — do not edit.",
    "# rust-analyzer does not always apply .cargo/config.local.toml [env] to build scripts.",
    "[cargo]",
    "extraEnv = {",
  ];
  for (const [key, value] of Object.entries(extraEnv)) {
    const keyToml = key.includes("-") ? `"${key}"` : key;
    lines.push(`  ${keyToml} = ${tomlEnvValue(value)},`);
  }
  lines.push("}", "");

  const out = path.join(JARVIS_ROOT, "rust-analyzer.toml");
  const body = lines.join("\n");
  if (writeIfChanged(out, body)) {
    console.log(`sync-cargo-win-env: wrote ${path.relative(JARVIS_ROOT, out)}`);
  }
}

function buildConfigTomlBody(discovered) {
  const lines = [
    "# Generated by scripts/sync-cargo-win-env.mjs — do not edit.",
    "# Lets bare `cargo check` / rust-analyzer build whisper-rs-sys without npm run tauri.",
    "# E0080 (usize overflow in bindings.rs) = bindgen failed; stale Linux fallback bindings.",
    "# CMAKE_GENERATOR matches tauri CUDA (Ninja/NMake) when toolkit present; VS 2022 if CPU-only.",
    "# Generator/cache mismatch after CPU↔CUDA: npm run cargo -- clean -p whisper-rs-sys --manifest-path src-tauri/Cargo.toml",
    "[env]",
  ];

  const envKeys = new Set([
    "CMAKE_GENERATOR",
    "CMAKE_MAKE_PROGRAM",
    "LIBCLANG_PATH",
    "BINDGEN_EXTRA_CLANG_ARGS",
    "BINDGEN_EXTRA_CLANG_ARGS_x86_64_pc_windows_msvc",
    "BINDGEN_EXTRA_CLANG_ARGS_x86_64-pc-windows-msvc",
  ]);

  for (const [key, value] of Object.entries(discovered)) {
    if (!envKeys.has(key)) continue;
    lines.push(`${key} = ${tomlEnvValue(value)}`);
  }

  const bindgen = discovered.BINDGEN_EXTRA_CLANG_ARGS;
  if (bindgen) {
    lines.push("");
    lines.push(`[target.${WINDOWS_TARGET}.env]`);
    lines.push(`BINDGEN_EXTRA_CLANG_ARGS = ${tomlEnvValue(bindgen)}`);
    lines.push(
      `BINDGEN_EXTRA_CLANG_ARGS_x86_64_pc_windows_msvc = ${tomlEnvValue(bindgen)}`,
    );
    lines.push(
      `BINDGEN_EXTRA_CLANG_ARGS_x86_64-pc-windows-msvc = ${tomlEnvValue(bindgen)}`,
    );
  }

  if (Object.keys(discovered).length === 0) {
    lines.push("# (no paths discovered — install VS 2022 Build Tools + LLVM, then re-run)");
  }

  return `${lines.join("\n")}\n`;
}

function writeIfChanged(filePath, body) {
  if (fs.existsSync(filePath)) {
    try {
      if (fs.readFileSync(filePath, "utf8") === body) {
        return false;
      }
    } catch {
      /* rewrite */
    }
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, body, "utf8");
  return true;
}

function writeConfigLocalToml(cargoDir, body) {
  const out = path.join(cargoDir, "config.local.toml");
  return { out, wrote: writeIfChanged(out, body) };
}

function main() {
  const localToml = path.join(TAURI_CARGO_DIR, "config.local.toml");
  const legacyRootCargo = path.join(JARVIS_ROOT, ".cargo", "config.local.toml");

  if (process.platform !== "win32") {
    if (fs.existsSync(legacyRootCargo)) {
      fs.unlinkSync(legacyRootCargo);
      console.log(`sync-cargo-win-env: removed ${path.relative(JARVIS_ROOT, legacyRootCargo)}`);
    }
    const reset = writeConfigLocalToml(
      TAURI_CARGO_DIR,
      "# Non-Windows: no whisper-rs-sys bindgen env required.\n[env]\n",
    );
    if (reset.wrote) {
      console.log(`sync-cargo-win-env: reset ${path.relative(JARVIS_ROOT, reset.out)}`);
    }
    const ra = path.join(JARVIS_ROOT, "rust-analyzer.toml");
    if (fs.existsSync(ra)) {
      fs.unlinkSync(ra);
      console.log(`sync-cargo-win-env: removed ${path.relative(JARVIS_ROOT, ra)}`);
    }
    return;
  }

  const check = validateWindowsWhisperBindgenEnv();
  if (!check.ok) {
    console.warn("sync-cargo-win-env: whisper-rs-sys bindgen prerequisites missing:");
    for (const e of check.errors) console.warn(`  - ${e}`);
    for (const w of check.warnings) console.warn(`  ${w}`);
  }

  const { discovered } = resolveBuildEnvironment({
    jarvisRoot: JARVIS_ROOT,
    channel: "sync",
    baseEnv: {},
    needsCuda: true,
    logPrefix: "sync-cargo-win-env",
  });

  const body = buildConfigTomlBody(discovered);

  const { out, wrote } = writeConfigLocalToml(TAURI_CARGO_DIR, body);
  const varCount = Object.keys(discovered).length;
  if (wrote) {
    console.log(
      `sync-cargo-win-env: wrote ${path.relative(JARVIS_ROOT, out)} (${varCount} vars)`,
    );
  } else {
    console.log(`sync-cargo-win-env: ${path.relative(JARVIS_ROOT, out)} unchanged`);
  }

  if (fs.existsSync(legacyRootCargo)) {
    fs.unlinkSync(legacyRootCargo);
    console.log(
      `sync-cargo-win-env: removed legacy ${path.relative(JARVIS_ROOT, legacyRootCargo)} (use src-tauri/.cargo include chain)`,
    );
  }

  writeRustAnalyzerToml(discovered);

  if (check.ok && discovered.BINDGEN_EXTRA_CLANG_ARGS) {
    console.log("sync-cargo-win-env: bindgen env OK (MSVC + Windows SDK includes for whisper-rs-sys)");
  }
}

main();
